export interface HumeRotheryAssessment {
  sizeDifferencePct: number;
  sizeCriterion: boolean;
  crystalStructureMatch: boolean;
  electronegativityDifference: number;
  electronegativityCriterion: boolean;
  valencyMatch: boolean;
  overallSolubilityForecast: "Complete / High Solid Solubility" | "Moderate / Partial Solubility" | "Low / Negligible Solubility (Forms Intermetallics / Two-Phase System)";
  explanation: string;
}

export function evaluateHumeRothery(el1: ElementData, el2: ElementData): HumeRotheryAssessment {
  const r1 = el1.atomicRadius;
  const r2 = el2.atomicRadius;
  const sizeDiffPct = Math.abs(r1 - r2) / Math.max(r1, r2) * 100;
  const sizeCriterion = sizeDiffPct < 15.0;

  const crystalStructureMatch = el1.crystalStructure === el2.crystalStructure && el1.crystalStructure !== "Other";
  const enDiff = Math.abs(el1.electronegativity - el2.electronegativity);
  const electronegativityCriterion = enDiff < 0.4;

  const valencyMatch = el1.valence.some(v => el2.valence.includes(v));

  let score = 0;
  if (sizeCriterion) score += 2;
  if (crystalStructureMatch) score += 2;
  if (electronegativityCriterion) score += 1;
  if (valencyMatch) score += 1;

  let forecast: HumeRotheryAssessment["overallSolubilityForecast"] = "Low / Negligible Solubility (Forms Intermetallics / Two-Phase System)";
  if (score >= 5) {
    forecast = "Complete / High Solid Solubility";
  } else if (score >= 3) {
    forecast = "Moderate / Partial Solubility";
  }

  const reasons = [];
  reasons.push(`Atomic radius difference is ${sizeDiffPct.toFixed(1)}% (${sizeCriterion ? "Passes <15% rule" : "Exceeds 15% limit"}).`);
  reasons.push(`Crystal structures: ${el1.symbol} (${el1.crystalStructure}) vs ${el2.symbol} (${el2.crystalStructure}) -> ${crystalStructureMatch ? "Matching lattice" : "Different lattice"}.`);
  reasons.push(`Electronegativity difference: Δχ = ${enDiff.toFixed(2)} (${electronegativityCriterion ? "Similar, solid solution favored" : "High difference, stable intermetallic compounds likely"}).`);

  return {
    sizeDifferencePct: Number(sizeDiffPct.toFixed(1)),
    sizeCriterion,
    crystalStructureMatch,
    electronegativityDifference: Number(enDiff.toFixed(2)),
    electronegativityCriterion,
    valencyMatch,
    overallSolubilityForecast: forecast,
    explanation: reasons.join(" "),
  };
}
